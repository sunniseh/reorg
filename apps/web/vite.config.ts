import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineConfig, loadEnv, type Plugin } from "vite";

const repo = fileURLToPath(new URL("../../", import.meta.url));
const ogCard = fileURLToPath(new URL("../../brand/social/og-card.png", import.meta.url));

/**
 * Link-preview card from the brand kit (brand/social/og-card.png, built by `npm run brand`).
 * Served in dev and emitted in the build as /og-card.png. Crawlers need absolute URLs, so the
 * og:image / og:url tags are injected only when VITE_PUBLIC_URL is set (no guessed deploy URL).
 */
function brandSocial(publicUrl: string): Plugin {
  const base = publicUrl.replace(/\/+$/, "");
  return {
    name: "reorg-brand-social",
    configureServer(server) {
      server.middlewares.use("/og-card.png", (_req, res) => {
        if (!existsSync(ogCard)) {
          res.statusCode = 404;
          res.end();
          return;
        }
        res.setHeader("content-type", "image/png");
        res.end(readFileSync(ogCard));
      });
    },
    generateBundle() {
      if (existsSync(ogCard)) this.emitFile({ type: "asset", fileName: "og-card.png", source: readFileSync(ogCard) });
    },
    transformIndexHtml() {
      if (!base) return [];
      return [
        { tag: "meta", attrs: { property: "og:url", content: `${base}/` }, injectTo: "head" },
        { tag: "meta", attrs: { property: "og:image", content: `${base}/og-card.png` }, injectTo: "head" },
        { tag: "meta", attrs: { property: "og:image:width", content: "1200" }, injectTo: "head" },
        { tag: "meta", attrs: { property: "og:image:height", content: "630" }, injectTo: "head" },
        { tag: "meta", attrs: { name: "twitter:image", content: `${base}/og-card.png` }, injectTo: "head" },
      ];
    },
  };
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, repo, "VITE_");
  return {
    // The atlas and palette live in the repo's art/ directory (one source for the art kit).
    server: { port: 5173, fs: { allow: [repo] } },
    // Favicons and the web manifest come from the brand kit (brand/icon, generated by `npm run brand`).
    publicDir: fileURLToPath(new URL("../../brand/icon", import.meta.url)),
    plugins: [brandSocial(env.VITE_PUBLIC_URL ?? "")],
    build: { target: "es2022", chunkSizeWarningLimit: 1500 },
  };
});
